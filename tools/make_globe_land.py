#!/usr/bin/env python3
"""Make globe_land.h for RADIO DAYS from Natural Earth 1:110m land polygons.

Usage:
    python3 make_globe_land.py ne_110m_land.geojson globe_land.h

Input: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
Natural Earth is in the public domain (naturalearthdata.com). "Made with Natural Earth."

Output: an equirectangular land mask, 256 x 128 cells (1.40625 degrees each),
one bit per cell, 32 bytes per row, row 0 = 90N, column 0 = 180W. A cell is land
when its centre lies inside a land polygon (even-odd rule; holes are lakes).
Rasterised row by row: edge crossings of the row's centre latitude, sorted, filled
between pairs.

SPDX-License-Identifier: MIT
"""
import json
import sys

W, H = 256, 128


def rings(geom):
    if geom["type"] == "Polygon":
        yield from geom["coordinates"]
    elif geom["type"] == "MultiPolygon":
        for poly in geom["coordinates"]:
            yield from poly


def main(src, dst):
    data = json.load(open(src))
    edges = []
    for feature in data["features"]:
        for ring in rings(feature["geometry"]):
            for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
                if y1 != y2:
                    edges.append((x1, y1, x2, y2))
    bits = [[0] * W for _ in range(H)]
    for row in range(H):
        lat = 90.0 - (row + 0.5) * 180.0 / H
        xs = []
        for x1, y1, x2, y2 in edges:
            if (y1 <= lat < y2) or (y2 <= lat < y1):
                xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            for col in range(W):
                lon = -180.0 + (col + 0.5) * 360.0 / W
                if a <= lon < b:
                    bits[row][col] ^= 1
    land = sum(map(sum, bits))
    with open(dst, "w") as f:
        f.write("// RADIO DAYS globe land mask, generated by tools/make_globe_land.py\n")
        f.write("// from Natural Earth 1:110m land (public domain). Made with Natural Earth.\n")
        f.write(f"// {W} x {H} cells, 1 bit each, row 0 = 90N, column 0 = 180W; {land} land cells.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"static constexpr int GLOBE_MAP_W = {W};\nstatic constexpr int GLOBE_MAP_H = {H};\n")
        f.write(f"static const uint8_t GLOBE_LAND[{H}][{W // 8}] = {{\n")
        for row in bits:
            vals = []
            for i in range(0, W, 8):
                v = 0
                for j in range(8):
                    v |= row[i + j] << (7 - j)
                vals.append(f"0x{v:02X}")
            f.write("    {" + ",".join(vals) + "},\n")
        f.write("};\n")
    print(f"{dst}: {land} land cells of {W * H} ({100.0 * land / (W * H):.1f}%)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
